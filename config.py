from pydantic_settings import BaseSettings

class Settings(BaseSettings):
    # Data paths
    DATA_PATH:             str = "data/processed/reviews_unified.parquet"
    RAW_DATA_PATH:         str = "data/raw"
    MODEL_PATH:            str = "models/distilbert-finetuned-final"
    INDEX_PATH:            str = "data/embeddings/reviews.faiss"
    EMBED_PATH:            str = "data/embeddings/review_embeddings.npy"
    LANGCHAIN_INDEX_PATH:  str = "data/embeddings/langchain_index"

    # MLflow (free, local) 
    MLFLOW_TRACKING_URI:  str = "mlruns"      #This tells MLflow where to save experiment data.URI is simply the address or location that MLflow uses to read and write experiment information.
    MLFLOW_EXPERIMENT:    str = "Feedback_Sentiment"  #This is simply the name of your experiment

    #Sentiment model 
    ROBERTA_MODEL: str = "cardiffnlp/twitter-roberta-base-sentiment-latest"

    # Logging
    LOG_LEVEL: str = "WARNING"

    #Embedding model configuration
    # Name of the pre-trained SentenceTransformer model.
    EMBEDDING_MODEL: str = "all-MiniLM-L6-v2"
    # Dimension of the embedding vector generated by the model.
    EMBEDDING_DIM: int = 384
    # Maximum number of tokens processed for each input text.
    MAX_SEQ_LENGTH:   int = 128

    # Retrieval
    TOP_K_RETRIEVAL: int = 6

    # API
    API_HOST:  str = "0.0.0.0"
    API_PORT:  int = 8000
    API_URL:   str = "http://localhost:8000"

    # Shared secret required in the `x-api-key` header on every /api/* route
    # except /api/health. Enforced by backend/api/deps.py, which refuses to
    # start if ENVIRONMENT=production and this is still the default below.
    API_KEY:   str = "dev-key-feedbackiq"   # override in production .env

    # Comma-separated CORS origins. "*" keeps local dev and docker-compose
    # working; set this to the deployed frontend's URL in production.
    ALLOWED_ORIGINS: str = "*"

    # LLM — no default keys here on purpose. A blank key makes a missing
    # .env entry an obvious, visible failure instead of quietly falling
    # back to a key that shouldn't be in source control at all.
    GOOGLE_API_KEY: str = ""
    GROQ_API_KEY:     str   = ""
    USE_GROQ:         bool  = True
    GROQ_MODEL:       str   = "llama-3.1-8b-instant"
    LLM_TEMPERATURE:  float = 0.2

    #Zero-shot complaint categorisation
    ZEROSHOT_MODEL:          str   = "MoritzLaurer/deberta-v3-base-zeroshot-v2.0"  # primary — outperforms BART-large-mnli on zero-shot benchmarks, esp. with larger label sets
    ZEROSHOT_BASELINE_MODEL: str   = "facebook/bart-large-mnli"                     # kept for baseline comparison / ablation
    CATEGORY_SHORTLIST_K:    int   = 6      # embedding-similarity shortlist size fed to the NLI reranker
    CATEGORY_CONFIDENCE_THRESHOLD: float = 0.35  # below this, return "Unclassified / Emerging Complaint"



    class Config:
        env_file = ".env"
        env_file_encoding = "utf-8"


settings = Settings()

